#[test]
fn original_strikes_keep_roles_callbacks_and_scene_cancellation() {
    for (kind, bytes, constants, duration, tick, power, contacts, clips) in [
        (
            Strike::LightningTiger,
            B313,
            C313,
            140,
            35,
            100,
            vec![80],
            vec![69, 70, 71],
        ),
        (
            Strike::FieryBeast,
            B315,
            C315,
            140,
            66,
            500,
            vec![12, 25],
            vec![57, 59, 67],
        ),
        (
            Strike::ThunderTiger,
            B317,
            C317,
            90,
            65,
            400,
            vec![0, 18, 48],
            vec![46, 47, 42, 50],
        ),
    ] {
        let mut bundle = Bundle::decode(bytes).unwrap();
        let parameters = decode_parameters(kind, constants).unwrap();
        let p = program(kind, &bundle, &parameters).unwrap();
        assert_eq!(
            (
                p.phases[0].action.duration,
                p.phases[1].action.duration,
                p.release_tick,
                p.projectile_rule.power
            ),
            (duration, 60, tick, power)
        );
        assert_eq!(
            p.phases[0]
                .action
                .hits
                .iter()
                .map(|h| h.start)
                .collect::<Vec<_>>(),
            contacts
        );
        assert_eq!(
            p.phases[0]
                .action
                .animations
                .commands()
                .filter_map(|command| match command {
                    AnimationCommand::Play { clip, .. } => Some(clip),
                    _ => None,
                })
                .collect::<Vec<_>>(),
            clips
        );
        assert!(p.phases[1].action.hits.is_empty() && p.phases[1].action.commands.is_empty());
        assert_eq!(p.direction, [1., 0., 0.]);
        assert_eq!(
            p.distance,
            if kind == Strike::LightningTiger {
                200.
            } else {
                100.
            }
        );
        assert_eq!(
            p.color,
            [
                16,
                16,
                16,
                if kind == Strike::ThunderTiger { 255 } else { 0 }
            ]
        );
        assert_eq!(
            p.projectile_heading,
            (kind != Strike::ThunderTiger).then_some(0.)
        );
        assert_eq!(
            p.projectile_height,
            (kind == Strike::ThunderTiger).then_some(0.)
        );
        assert_eq!(
            p.initial_effect_scale,
            (kind != Strike::LightningTiger).then_some(1.)
        );
        bundle.phases[2].duration = 1;
        assert!(program(kind, &bundle, &parameters).is_err());
    }
    let fiery = program(
        Strike::FieryBeast,
        &Bundle::decode(B315).unwrap(),
        &decode_parameters(Strike::FieryBeast, C315).unwrap(),
    )
    .unwrap();
    assert!(
        fiery.phases[0].action.duration > 135,
        "Fiery Beast's source scene cancels its longer track"
    );
    let thunder = program(
        Strike::ThunderTiger,
        &Bundle::decode(B317).unwrap(),
        &decode_parameters(Strike::ThunderTiger, C317).unwrap(),
    )
    .unwrap();
    assert_eq!(
        thunder.phases[0]
            .action
            .audio_ids()
            .1
            .into_iter()
            .collect::<Vec<_>>(),
        [108, 112]
    );
}
