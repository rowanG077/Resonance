//! Native shared model and motion resources. Names preserve the cooker catalog;
//! motion labels describe resource identity, not an inferred animation behavior.

// Shared TPL images cooked by importer/src/field_overlays.rs. These packed
// resource IDs name overlays rather than models or motion banks.
ids! { pub enum FieldOverlayId: u32 {
    RadialBurst = 68611 => "effects/overlays/radial-burst",
    OrnateRing = 68614 => "effects/overlays/ornate-ring",
} }

impl FieldOverlayId {
    pub const fn repeats(self) -> bool {
        matches!(self, Self::OrnateRing)
    }

    pub fn texture_path(self) -> String {
        format!(
            "{}.ktx2",
            self.resource_name().expect("overlay publication name")
        )
    }

    pub fn scene_path(self) -> String {
        format!(
            "{}.json",
            self.resource_name().expect("overlay publication name")
        )
    }
}

